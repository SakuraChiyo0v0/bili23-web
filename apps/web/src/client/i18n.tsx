const DICTS: Record<Lang, Partial<Record<I18nKey, string>>> = {
  "zh-CN": zhCN,
  "zh-TW": zhTW,
  en,
};

/** navigator.language 前缀 → 界面语言（zh→zh-CN；zh-TW/zh-HK→zh-TW；其余→en） */
export function langFromNavigator(language: string | undefined): Lang {
  const raw = (language ?? "").toLowerCase().replace("_", "-");
  if (raw.startsWith("zh")) {
    if (raw.startsWith("zh-tw") || raw.startsWith("zh-hk") || raw.startsWith("zh-mo") || raw.startsWith("zh-hant")) {
      return "zh-TW";
    }
    return "zh-CN";
  }
  return "en";
}

/** 语言偏好 → 实际字典语言（system 时按浏览器解析） */
export function resolveLang(pref: LangPref): Lang {
  if (pref !== "system") return pref;
  if (typeof navigator === "undefined") return "zh-CN";
  return langFromNavigator(navigator.language);
}

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key]) : match));
}

interface I18nValue {
  /** 用户偏好（含 system） */
  pref: LangPref;
  /** 实际生效语言 */
  lang: Lang;
  setPref: (pref: LangPref) => void;
  /** 取文案；zh-TW / en 缺 key 时回退 zh-CN；仍缺则返回 key 本身 */
  t: (key: I18nKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

/**
 * 语言 Provider：
 * - 初始跟随浏览器，避免等待配置期间闪烁；
 * - 挂载后从 GET /api/config 读取 config.behavior.language（未取到/非法保持默认）；
 * - 同步 <html lang>。
 */
export function I18nProvider({ children }: { children: ReactNode }) {
  const [pref, setPrefState] = useState<LangPref>("system");
  const lang = useMemo<Lang>(() => resolveLang(pref), [pref]);

  useEffect(() => {
    let alive = true;
    fetch("/api/config")
      .then((res) =>
        res.ok ? (res.json() as Promise<{ config?: { behavior?: { language?: unknown } } }>) : null,
      )
      .then((json) => {
        const language = json?.config?.behavior?.language;
        if (
          alive &&
          (language === "zh-CN" || language === "zh-TW" || language === "en" || language === "system")
        ) {
          setPrefState(language);
        }
      })
      .catch(() => {
        // 配置读取失败：保持默认（跟随浏览器）
      });
    return () => {
      alive = false;
    };
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setPref = useCallback((next: LangPref): void => {
    setPrefState(next);
  }, []);

  const t = useCallback(
    (key: I18nKey, vars?: Record<string, string | number>): string => {
      const dict = DICTS[lang];
      const raw = dict?.[key] ?? zhCN[key] ?? key;
      return interpolate(raw, vars);
    },
    [lang],
  );

  const value = useMemo<I18nValue>(() => ({ pref, lang, setPref, t }), [pref, lang, setPref, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n 必须在 <I18nProvider> 内使用");
  return ctx;
}